
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CONTRACT_PATH = REPO / "products" / "caseforge-client-viewer" / "lib" / "hubContract.json"
PREFIX = "/client-viewer"


def _refs(node, found: set[str]) -> None:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            found.add(ref.rsplit("/", 1)[1])
        for value in node.values():
            _refs(value, found)
    elif isinstance(node, list):
        for value in node:
            _refs(value, found)


def _strip(node, names_are_fields: bool = False):
    if isinstance(node, dict):
        return {
            k: _strip(v, names_are_fields=(k == "properties" and not names_are_fields))
            for k, v in node.items()
            if names_are_fields or k not in {"title", "description", "examples", "example"}
        }
    if isinstance(node, list):
        return [_strip(v) for v in node]
    return node


def build_contract() -> dict:
    sys.path.insert(0, str(REPO / "tools"))
    os.environ.setdefault("CASEFORGE_CHAT_API_TOKEN", "contract-export-not-a-secret")
    from vergil.api import create_app

    spec = create_app().openapi()
    routes: dict[str, dict] = {}
    wanted: set[str] = set()
    for path, operations in spec["paths"].items():
        if not path.startswith(PREFIX):
            continue
        for method, operation in operations.items():
            content = operation.get("responses", {}).get("200", {}).get("content", {})
            schema = content.get("application/json", {}).get("schema")
            if not schema:
                continue
            routes[f"{method.upper()} {path}"] = _strip(schema)
            _refs(schema, wanted)
    components = spec.get("components", {}).get("schemas", {})
    closure: set[str] = set()
    todo = list(wanted)
    while todo:
        name = todo.pop()
        if name in closure or name not in components:
            continue
        closure.add(name)
        more: set[str] = set()
        _refs(components[name], more)
        todo.extend(more - closure)
    return {
        "_note": "Generated by tools/vergil/hub_contract.py from the hub's OpenAPI schema. Do not edit by hand.",
        "routes": dict(sorted(routes.items())),
        "components": {name: _strip(components[name]) for name in sorted(closure)},
    }


def render(contract: dict) -> str:
    return json.dumps(contract, indent=1, sort_keys=True) + "\n"


def main(argv: list[str]) -> int:
    text = render(build_contract())
    if "--check" in argv:
        current = CONTRACT_PATH.read_text(encoding="utf-8") if CONTRACT_PATH.exists() else ""
        if current != text:
            print(f"{CONTRACT_PATH.relative_to(REPO)} is stale: run python3 tools/vergil/hub_contract.py", file=sys.stderr)
            return 1
        return 0
    CONTRACT_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {CONTRACT_PATH.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
