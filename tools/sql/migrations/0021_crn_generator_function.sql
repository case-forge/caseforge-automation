
CREATE OR REPLACE FUNCTION caseforge_next_company_reference(ref_date DATE)
RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
    prefix TEXT := to_char(ref_date, 'YYMMDD');
    max_seq INTEGER;
BEGIN

    PERFORM pg_advisory_xact_lock(hashtext('caseforge_company_reference:' || prefix));

    SELECT COALESCE(MAX(seq), 0) INTO max_seq
    FROM (
        SELECT (regexp_match(company_reference, '^' || prefix || '/(\d{2})FL$'))[1]::INTEGER AS seq
        FROM matters
        WHERE company_reference LIKE prefix || '/%FL'
        UNION ALL
        SELECT (regexp_match(ref_value, '^' || prefix || '/(\d{2})FL$'))[1]::INTEGER AS seq
        FROM matter_references
        WHERE ref_type = 'company_ref' AND ref_value LIKE prefix || '/%FL'
    ) seqs;

    RETURN prefix || '/' || lpad((max_seq + 1)::TEXT, 2, '0') || 'FL';
END;
$$;

CREATE OR REPLACE FUNCTION caseforge_ensure_company_reference(p_matter_id INTEGER)
RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
    existing TEXT;
    ref_date DATE;
    new_ref TEXT;
    now_ts TEXT := to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"');
BEGIN
    SELECT NULLIF(company_reference, ''),
           COALESCE(NULLIF(referral_sent_at, ''), NULLIF(source_email_sent_at, ''), LEFT(created_utc, 10))::DATE
    INTO existing, ref_date
    FROM matters WHERE matter_id = p_matter_id;

    IF existing IS NOT NULL THEN
        RETURN existing;
    END IF;
    IF NOT FOUND OR ref_date IS NULL THEN

        RAISE EXCEPTION USING MESSAGE =
            'matter ' || p_matter_id::TEXT || ' has no referral/created date to generate a CaseForge reference from';
    END IF;

    new_ref := caseforge_next_company_reference(ref_date);
    UPDATE matters SET company_reference = new_ref WHERE matter_id = p_matter_id;

    UPDATE matter_references SET is_primary = 0, updated_utc = now_ts
        WHERE matter_id = p_matter_id AND ref_type = 'company_ref';

    IF EXISTS (
        SELECT 1 FROM matter_references
        WHERE matter_id = p_matter_id AND ref_type = 'company_ref' AND ref_value_normalised = upper(new_ref)
    ) THEN
        UPDATE matter_references
        SET ref_value = new_ref, source = 'notice_of_acting',
            notes = 'Generated by caseforge_ensure_company_reference()', is_primary = 1, updated_utc = now_ts
        WHERE matter_id = p_matter_id AND ref_type = 'company_ref' AND ref_value_normalised = upper(new_ref);
    ELSE
        INSERT INTO matter_references (
            matter_id, ref_type, ref_value, ref_value_normalised, source, notes,
            is_primary, created_utc, updated_utc
        ) VALUES (
            p_matter_id, 'company_ref', new_ref, upper(new_ref), 'notice_of_acting',
            'Generated by caseforge_ensure_company_reference()', 1, now_ts, now_ts
        );
    END IF;

    RETURN new_ref;
END;
$$;
