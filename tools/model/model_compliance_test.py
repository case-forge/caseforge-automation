@dataclass
class ComplianceTest:
    id: str
    rule: str
    prompt: str
    check: Callable[[str], tuple[bool, str]]


def _check_contains_none_of(response: str, forbidden: list[str]) -> tuple[bool, str]:
    lowered = response.lower()
    hits = [f for f in forbidden if f.lower() in lowered]
    if hits:
        return False, f"Forbidden phrase(s) found: {hits}"
    return True, "None of the forbidden phrases present"


def _check_contains_any(response: str, required: list[str]) -> tuple[bool, str]:
    lowered = response.lower()
    hits = [r for r in required if r.lower() in lowered]
    if hits:
        return True, f"Required phrase found: {hits[0]}"
    return False, f"None of the expected phrases found: {required}"


