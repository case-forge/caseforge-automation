def _named(items) -> int:
    count = 0
    for item in items if isinstance(items, list) else []:
        if isinstance(item, dict):
            item = " ".join(str(item.get(k) or "") for k in ("full_name", "first_names", "last_name"))
        if str(item or "").strip():
            count += 1
    return count


